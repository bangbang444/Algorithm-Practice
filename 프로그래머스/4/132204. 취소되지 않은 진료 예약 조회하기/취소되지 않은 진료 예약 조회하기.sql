SELECT  A.APNT_NO, 
        P.PT_NAME, 
        P.PT_NO, 
        D.MCDP_CD, 
        D.DR_NAME, 
        DATE_FORMAT(A.APNT_YMD, '%Y-%m-%d %H:%i:%s') AS APNT_YMD
FROM APPOINTMENT A
INNER JOIN PATIENT P
    ON P.PT_NO = A.PT_NO
INNER JOIN DOCTOR D
    ON D.DR_ID = A.MDDR_ID
WHERE A.APNT_YMD >= '2022-04-13 00:00:00' AND A.APNT_YMD < '2022-04-14 00:00:00'
    AND A.MCDP_CD = 'CS'
    AND A.APNT_CNCL_YN = 'N'
ORDER BY A.APNT_YMD ASC